/*
 * foc_loop.h
 *
 * FOC common type definitions:
 *   1. Signal structs  — Data passed between modules (corresponding to Simulink diagram connections), used only as ISR local variables
 *   2. State structs   — Global instance types for motor / foc / prot / telem
 *
 * Note: The debug fields (angle_now, current_phase, filtered_Iq, filtered_RPM,
 * last_percent, percent_torque_requested, voltage_power_supply, zero_electric_angle,
 * T_Mot, report_DCA) are for Live Watch use. Do not rename or delete them.
 */

#ifndef INC_FOC_LOOP_H_
#define INC_FOC_LOOP_H_

#include <stdint.h>
#include <stdbool.h>
#include "config.h"            // HW_OC_TIME, SOFT_OC_TIME, ENC_TIME

/* ================================================================
 *  Part 1 — Signal structs (ISR local variables, passed between modules via parameters / return values)
 * ================================================================ */

typedef struct { float a, b, c; }       abc_t;     // Three-phase quantities (V or A)
typedef struct { float alpha, beta; }   ab_t;      // Stationary frame α-β
typedef struct { float d, q; }          dq_t;      // Rotating frame d-q
typedef struct { float Da, Db, Dc; }    duty_t;    // PWM duty cycle 0~1

/* [1a] ADC snapshot — Copied from DMA_ADCx_arr by sensing_read_raw() */
typedef struct {
    uint16_t adc1[4];          // Ia, Ib, Ic, Idc
    uint16_t adc2[4];          // sin+, sin-, cos+, cos-
    uint16_t adc3[6];          // Vdc, T_MCU, T_Mot, T_U, T_V, T_W
} adc_raw_t;

/* [1b] Measurement results — Generated by sensing_process()
 * Phase currents, PLL angle, speed and Vdc are written directly to the globals
 * foc.current_phase[], foc.angle_now, foc.filtered_RPM, motor.voltage_power_supply. */
typedef struct {
    float theta_e;             // Electrical angle (rad, zero_electric_angle subtracted)
    float sin_e, cos_e;        // sin/cos(theta_e), shared by Park and inverse Park (= Simulink sinE/cosE)
    float omega_e;             // Electrical angular velocity (rad/s)
} foc_meas_t;

/* ================================================================
 *  Part 2 — State structs (global instances defined in main.c)
 * ================================================================ */

/* ---- motor_params_t: Motor physical parameters and system parameters ---- */
typedef struct {
    /* --- Motor physical constants (immutable after init) --- */
    float const Rs;                    // Stator resistance  (Ohm)
    float const Ld;                    // D-axis inductance  (H)
    float const Lq;                    // Q-axis inductance  (H)
    float const flux_linkage_m;        // PM flux linkage    (Wb)
    float const electrical_constant;   // Back-EMF constant  (V/(rad/s))
    float const max_current;           // Phase current limit (A)
    float const max_Torque;            // Max torque (Nm)
    int   const pole_pairs;            // Number of pole pairs
    int   const dir;                   // Rotation direction (CCW = 1, CW = -1)
    float const Ts;                    // Control-loop period (s)

    /* --- Runtime-writable fields --- */
    float zero_electric_angle;         // [debug] Encoder zero-offset (rad)
    float voltage_power_supply;        // [debug] DC bus voltage (V)
    float voltage_limit;               // Modulation voltage limit (V)
} motor_params_t;

/* ---- foc_state_t: FOC real-time state ---- */
typedef struct {
    /* --- Electrical angle & position --- */
    float angle_now;                   // [debug] PLL angle (rad)
    float zero_cross;

    /* --- Measured / filtered signals --- */
    float    filtered_RPM;             // [debug]
    float    filtered_Iq;              // [debug]
    float    filtered_Id;
    uint16_t current_offset[4];        // ADC1 zero-point (calibrated at startup)
    float    current_phase[3];         // [debug] Phase currents (A)

    /* --- Controller outputs --- */
    float Iq_controller_output;        // Vq (read by Torque_cmd before update = Simulink Feedback)
    float Id_controller_output;        // Vd
    float phase_dc[3];                 // DC-offset loop: LPF'd phase currents (A)
    float Iabc_controller_output[3];   // DC-offset loop: PI output per phase (V)

    /* --- Control targets --- */
    float target_Iq;
    float target_Id;
    float Id_fw;
    float Iq_fw;
    float Id_MTPA;

    /* --- Torque request & ramp --- */
    float percent_torque_requested;    // [debug] CAN command
    float percent_power_requested;
    float last_percent;                // [debug] Actual command after ramp / regen / derate
    float abs_last_percent;
    float max_ramp;

    /* --- Flags --- */
    int           enable_hw_oc;
    uint8_t       enable_dc_control;
    uint8_t       fast_stop_enable;
    uint8_t       run;
    volatile bool enable_regen;

    /* --- Hardware config --- */
    int period;                        // PWM half-period (timer counts)
    int freq;                          // Control frequency (Hz)
} foc_state_t;

/* ---- protection_t: Sliding window protection buffers (instance is static in foc_protection.c) ---- */
typedef struct {
    /* Hardware OC sliding window */
    uint8_t  oc_buf[HW_OC_TIME];
    uint16_t oc_index;
    uint16_t oc_sum;

    /* Software OC sliding window */
    uint8_t  soft_oc_buf[SOFT_OC_TIME];
    uint16_t soft_oc_index;
    uint16_t soft_oc_sum;

    /* Encoder error sliding window */
    uint8_t  enc_buf[ENC_TIME];
    uint16_t enc_index;
    uint16_t enc_sum;

    /* Moving RMS (3 phases x 10 000 samples) */
    int16_t  RMS_buf[3][10000];
    uint32_t RMS_sum[3];
    uint16_t indexRMS;
} protection_t;

/* ---- telemetry_t: CAN report / logging ---- */
typedef struct {
    /* Temperatures (x10 °C) */
    int16_t T_Report;
    int16_t T_Mot;                     // [debug]
    int16_t T_MCU;
    int16_t T_U;
    int16_t T_V;
    int16_t T_W;

    /* CAN report fields */
    uint16_t report_status;
    uint16_t report_DCV;               // DC voltage (x100 V)
    int16_t  report_DCA;               // [debug] DC current (x100 A)

    /* Logging variables */
    int16_t IU_100;
    int16_t IV_100;
    int16_t IW_100;
} telemetry_t;

/* ================================================================
 *  Extern declarations
 *  Only debug / Live Watch variables stay global here.
 *  PID / LPF instances and prot are owned (static) by their modules.
 * ================================================================ */

/* --- Struct instances (defined in main.c) --- */
extern motor_params_t   motor;
extern foc_state_t      foc;
extern telemetry_t      telem;

/* --- DMA ADC buffers (defined in adc.c, special memory sections) --- */
extern uint16_t DMA_ADC1_arr[4];
extern uint16_t DMA_ADC2_arr[4];
extern uint16_t DMA_ADC3_arr[6];

/* --- TIMING debug (shared with main.c while-loop) --- */
#ifdef TIMING
extern int       max_time;
extern int       min_time;
extern int       prev_time;
extern int       max_btw;
extern int       max_sdwrite;
extern uint32_t  loop_time;
extern int       indexTimer;
#endif

#endif /* INC_FOC_LOOP_H_ */
